#!/bin/bash
# Rewrites THIRD_PARTY_LICENSES.md: every crate the two shipped programs are built
# from (normal and build dependencies, as locked in Cargo.lock), with the license
# its own manifest declares. Run it after changing dependencies.
set -euo pipefail

repo_root="$(cd "$(dirname "$0")/.." && pwd -P)"
out="$repo_root/THIRD_PARTY_LICENSES.md"

rows="$(cargo tree --manifest-path "$repo_root/Cargo.toml" --locked --workspace \
  --edges normal,build --prefix none --format '{p}|{l}|{r}' \
  | sed 's/ (\*)$//' | grep -v "($repo_root" | grep -v '^$' | sort -u)"

{
  cat <<'HEAD'
# Third-party licenses

Agent Video Studio is MIT licensed (see `LICENSE`). The editor and the MCP server
are built from the crates below. This list is generated by
`scripts/third-party-licenses.sh` from `Cargo.lock`; do not edit it by hand.

Where a crate offers a choice of licenses, Agent Video Studio uses it under the
most permissive one offered (MIT, Apache-2.0, BSD, Zlib, or similar), never a
GPL or LGPL option.

Fonts: `epaint_default_fonts` embeds four fonts in the editor binary: Ubuntu-Light
(`UFL.txt`), Hack-Regular (`Hack-Regular.txt`), NotoEmoji-Regular (`OFL.txt`) and
emoji-icon-font (`emoji-icon-font-mit-license.txt`). A binary distribution must
carry those license texts; the named files are in that crate's `fonts/` folder.
The editor's own text is drawn with the system's Hiragino font, which is not
distributed with it.

Not included: `ffmpeg` and `ffprobe` are separate programs the user installs;
Agent Video Studio starts them and does not contain or link them.

| Crate | Version | License | Source |
|---|---|---|---|
HEAD
  printf '%s\n' "$rows" | while IFS='|' read -r package license repository; do
    name="${package%% *}"
    version="${package#* }"
    version="${version%% *}"
    printf '| %s | %s | %s | %s |\n' "$name" "${version#v}" "${license:-not declared}" "${repository:--}"
  done
} > "$out.new"
mv "$out.new" "$out"
printf '%s\n' "$out"
